-- 1. Tabla de Proveedores
create table if not exists public.proveedores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  telefono text not null,
  email text not null,
  creado timestamptz not null default now()
);

-- 2. Tabla de Artículos (con clave foránea hacia proveedores)
create table if not exists public.articulos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  categoria text not null,
  precio numeric(12, 2) not null check (precio >= 0),
  stock integer not null default 0 check (stock >= 0),
  imagen_url text,
  proveedor_id bigint references public.proveedores(id) on delete set null,
  creado timestamptz not null default now()
);

-- 3. Habilitar Row Level Security (RLS)
alter table public.proveedores enable row level security;
alter table public.articulos enable row level security;

-- 4. Permisos de acceso público para uso educativo (rol anon y authenticated)
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.proveedores to anon, authenticated;
grant select, insert, update, delete on public.articulos to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Eliminar políticas previas si existieran para permitir re-ejecución limpia
drop policy if exists "Acceso publico proveedores" on public.proveedores;
drop policy if exists "Acceso publico articulos" on public.articulos;

create policy "Acceso publico proveedores"
  on public.proveedores
  for all
  to anon, authenticated
  using (true)
  with check (true);

create policy "Acceso publico articulos"
  on public.articulos
  for all
  to anon, authenticated
  using (true)
  with check (true);

